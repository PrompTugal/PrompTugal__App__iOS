"""Builds listing.json from listing-en.md, listing-pt-PT.md and listing-pt-BR.md (the source of truth).
Run from this folder: python3 make_listing_json.py. Fails if a field is over Apple's limit (keywords in bytes),
still carries an "only if merged" marker, or names the event's trademark."""
import json
import re

FILES = {
    "en-US": ("listing-en.md", ["Name (30)", "Subtitle (30)", "Promotional text (170)", "Description (4000)", "Keywords (100)", "What's new (4000)"]),
    "pt-PT": ("listing-pt-PT.md", ["Nome (30)", "Subtítulo (30)", "Texto promocional (170)", "Descrição (4000)", "Palavras-chave (100)", "Novidades (4000)"]),
    "pt-BR": ("listing-pt-BR.md", ["Nome (30)", "Subtítulo (30)", "Texto promocional (170)", "Descrição (4000)", "Palavras-chave (100)", "Novidades (4000)"]),
}
NAMES = ["name", "subtitle", "promotionalText", "description", "keywords", "whatsNew"]
LIMITS = {"name": 30, "subtitle": 30, "promotionalText": 170, "description": 4000, "keywords": 100, "whatsNew": 4000}


def sections(path):
    text = open(path, encoding="utf-8").read()
    out = {}
    for part in re.split(r"\n## ", text)[1:]:
        head, _, body = part.partition("\n")
        out[head.strip()] = body
    return out


def value(body):
    fenced = re.search(r"```\n(.*?)\n```", body, re.S)
    return fenced.group(1) if fenced else body.strip().split("\n\n")[0].strip()


def urls(body):
    found = [m.group(1) for m in re.finditer(r"\| [^|]+ \| (https://\S+) \|", body)]
    return {"supportUrl": found[0], "marketingUrl": found[1], "privacyPolicyUrl": found[2]}


def main():
    result = {
        "_about": "Generated by make_listing_json.py from the listing-*.md files. Field names follow the App Store Connect API: "
                  "appInfoLocalizations (name, subtitle, privacyPolicyUrl) and appStoreVersionLocalizations (description, keywords, "
                  "promotionalText, whatsNew, supportUrl, marketingUrl).",
        "locales": {},
    }
    for locale, (path, heads) in FILES.items():
        parts = sections(path)
        fields = {name: value(parts[head]) for name, head in zip(NAMES, heads)}
        fields.update(urls(parts["URLs"]))
        for name, limit in LIMITS.items():
            size = len(fields[name].encode()) if name == "keywords" else len(fields[name])
            assert size <= limit, f"{locale} {name}: {size} > {limit}"
            assert "only if merged" not in fields[name] and "se integrado" not in fields[name], f"{locale} {name}: marker left"
            assert not re.search(r"web ?summit", fields[name], re.I), f"{locale} {name}: trademark"
        result["locales"][locale] = fields
    # The record's primary locale is en-GB (its only existing localization): same English text as en-US.
    # "program" stays as is: "programme" would push the subtitle past 30 characters.
    result["locales"]["en-GB"] = dict(result["locales"]["en-US"])
    # A first App Store version takes no "What's New"; keep it here for later versions, but asc.py skips it on 1st release.
    result["whatsNewOnFirstVersion"] = False
    # The App Store version's copyright line (asc.py store-metadata reads it; --copyright overrides). Bump the year as needed.
    result["copyright"] = "2026 PrompTugal"
    with open("listing.json", "w", encoding="utf-8") as out:
        json.dump(result, out, ensure_ascii=False, indent=2)
        out.write("\n")
    for locale, fields in result["locales"].items():
        print(locale, {k: len(v) for k, v in fields.items()})


if __name__ == "__main__":
    main()
