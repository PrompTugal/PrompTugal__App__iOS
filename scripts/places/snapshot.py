#!/usr/bin/env python3
"""Copy PrompTugal.news by place into the app: data/by-place/<id>.json for Portugal, the Algarve and its 17 towns.

Writes Packages/PTLocal/Sources/PTLocal/Resources/place-<id>.json (the files as published, unchanged) and
LocalSnapshot.swift (the day they were read). The app shows that day on every screen that uses the copy, and
replaces it with the live files when it can reach promptugal.news. Standard library only.

Usage: python3 -I scripts/places/snapshot.py [--check]
  --check  fail if a bundled file no longer parses or a place is missing (no network).
"""
import datetime
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'Packages/PTLocal/Sources/PTLocal/Resources'
SWIFT = ROOT / 'Packages/PTLocal/Sources/PTLocal/LocalSnapshot.swift'
BASE = 'https://promptugal.news/data/by-place/'
# Keep in step with PlaceDirectory in PlaceModels.swift.
PLACES = ['portugal', 'algarve', 'faro', 'loule', 'quarteira', 'silves', 'tavira', 'vila-real-de-santo-antonio',
          'portimao', 'lagos', 'olhao', 'albufeira', 'lagoa', 'monchique', 'aljezur', 'vila-do-bispo',
          'castro-marim', 'alcoutim', 'sao-bras-de-alportel']
REQUIRED = ['id', 'name', 'kind', 'parent', 'mandate', 'status', 'updated', 'by']


def valid(place, data):
    doc = json.loads(data)
    missing = [k for k in REQUIRED if k not in doc]
    if missing:
        raise ValueError(f'{place}: missing {missing}')
    if doc['id'] != place:
        raise ValueError(f'{place}: id is {doc["id"]}')
    return doc


def check():
    errors = []
    for place in PLACES:
        path = OUT / f'place-{place}.json'
        try:
            valid(place, path.read_bytes())
        except Exception as e:  # noqa: BLE001
            errors.append(f'{path.name}: {e}')
    if not SWIFT.exists():
        errors.append('LocalSnapshot.swift is missing')
    for e in errors:
        print('error:', e)
    return 1 if errors else 0


def main(argv):
    if '--check' in argv:
        return check()
    OUT.mkdir(parents=True, exist_ok=True)
    for place in PLACES:
        req = urllib.request.Request(BASE + place + '.json', headers={'User-Agent': 'PrompTugal-iOS-snapshot'})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = r.read()
        doc = valid(place, data)
        (OUT / f'place-{place}.json').write_bytes(data)
        print(f'{place}: {doc["status"]}, {len(doc.get("ai_news", []))} stories, {len(doc.get("ai_map", []))} on the map')
    day = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')
    SWIFT.write_text(
        '// Generated by scripts/places/snapshot.py: the day the built-in place files were read.\n'
        'enum LocalSnapshot {\n'
        f'    static let day = "{day}"\n'
        '}\n', encoding='utf-8')
    print('snapshot day', day)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
